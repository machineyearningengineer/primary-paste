import AppKit
import Foundation

final class ClipboardObserver {
    private let primaryStore: PrimarySelectionStore
    private let preferences: PreferencesStore
    private let clipboardRestorer: ClipboardRestorer
    private let appRules: AppRulesEngine
    private let privacyFilter: PrivacyFilter
    private let diagnostics: InteractionDiagnostics
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var programmaticSuppression = ClipboardSuppressionState()

    init(
        primaryStore: PrimarySelectionStore,
        preferences: PreferencesStore,
        clipboardRestorer: ClipboardRestorer,
        appRules: AppRulesEngine,
        privacyFilter: PrivacyFilter,
        diagnostics: InteractionDiagnostics
    ) {
        self.primaryStore = primaryStore
        self.preferences = preferences
        self.clipboardRestorer = clipboardRestorer
        self.appRules = appRules
        self.privacyFilter = privacyFilter
        self.diagnostics = diagnostics
    }

    func start() {
        stop()
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.45, repeats: true) { [weak self] _ in
            self?.pollClipboard()
        }
        if let timer {
            RunLoop.main.add(timer, forMode: .common)
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func suppressProgrammaticChanges(reason: String = "programmatic clipboard write", duration: TimeInterval = 3.0) {
        programmaticSuppression.suppressProgrammaticChanges(
            reason: reason,
            duration: duration,
            changeCountAtStart: NSPasteboard.general.changeCount,
            expectedObservedChanges: 2
        )
    }

    func adoptCurrentPasteboardState() {
        programmaticSuppression.clear()
        lastChangeCount = NSPasteboard.general.changeCount
    }

    private func pollClipboard() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        guard preferences.isEnabled else {
            diagnostics.recordClipboardDecision("Ignored clipboard change because Primary Paste is paused")
            return
        }
        if let suppressionReason = suppressedProgrammaticClipboardReason() {
            let decision = "Ignored programmatic clipboard change: \(suppressionReason)"
            diagnostics.recordClipboardDecision(decision)
            if suppressionReason.hasPrefix("clipboard link probe") {
                diagnostics.recordClipboardSelfCaptureProbe(decision, passed: true)
            }
            return
        }
        guard !preferences.isPrivateModeEnabled else {
            diagnostics.recordClipboardDecision("Ignored clipboard change because Private Mode is on")
            return
        }
        guard preferences.clipboardLinkMode.importsClipboardCopies else {
            diagnostics.recordClipboardDecision("Clipboard link is \(preferences.clipboardLinkMode.title)")
            return
        }
        guard !appRules.isScreenLocked else {
            diagnostics.recordClipboardDecision("Ignored clipboard change because screen is locked")
            return
        }
        guard appRules.canCaptureFrontmostApp() else {
            diagnostics.recordClipboardDecision("Blocked for \(appRules.frontmostAppName)")
            return
        }

        let snapshot = clipboardRestorer.snapshot()
        guard !snapshot.isTransient else {
            diagnostics.recordClipboardDecision("Ignored transient, autogenerated, or concealed clipboard content")
            return
        }
        guard !snapshot.isEmpty else {
            diagnostics.recordClipboardDecision("Ignored empty clipboard payload")
            return
        }

        if preferences.plainTextOnly {
            guard
                let text = snapshot.plainText
            else {
                diagnostics.recordClipboardDecision("Ignored non-text clipboard payload because plain text only is on")
                return
            }

            switch privacyFilter.decision(for: text) {
            case .allowed:
                break
            case .denied(let reason):
                diagnostics.recordClipboardDecision("Ignored clipboard text: \(reason.diagnosticDescription)")
                return
            }

            primaryStore.record(
                text,
                sourceAppName: appRules.frontmostAppName,
                sourceBundleIdentifier: appRules.frontmostBundleIdentifier,
                isClipboardCopy: true
            )
            diagnostics.recordClipboardDecision("Captured clipboard text from \(appRules.frontmostAppName)")
            return
        }

        if let denialReason = snapshotDenialReason(snapshot) {
            diagnostics.recordClipboardDecision("Ignored clipboard payload: \(denialReason.diagnosticDescription)")
            return
        }
        primaryStore.record(
            snapshot,
            sourceAppName: appRules.frontmostAppName,
            sourceBundleIdentifier: appRules.frontmostBundleIdentifier
        )
        diagnostics.recordClipboardDecision("Captured clipboard payload from \(appRules.frontmostAppName)")
    }

    private func suppressedProgrammaticClipboardReason() -> String? {
        programmaticSuppression.suppressedProgrammaticClipboardReason(
            currentChangeCount: NSPasteboard.general.changeCount
        )
    }

    private func snapshotDenialReason(_ snapshot: PasteboardSnapshot) -> PrivacyFilterDenialReason? {
        for item in snapshot.items {
            guard let text = item.string(forType: .string) else { continue }
            if case .denied(let reason) = privacyFilter.decision(for: text) {
                return reason
            }
        }
        return nil
    }
}
