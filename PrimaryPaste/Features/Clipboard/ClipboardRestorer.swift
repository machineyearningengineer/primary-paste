import AppKit
import Foundation

enum ClipboardRestorePolicy {
    static func shouldRestore(stagedChangeCount: Int, currentChangeCount: Int) -> Bool {
        stagedChangeCount == currentChangeCount
    }
}

struct PasteboardSnapshot {
    let items: [NSPasteboardItem]
    let fileURLs: [URL]

    init(items: [NSPasteboardItem], fileURLs: [URL] = []) {
        self.items = items
        self.fileURLs = fileURLs
    }

    var isEmpty: Bool {
        items.isEmpty && fileURLs.isEmpty
    }

    var previewText: String {
        if let fileSelectionPreview = fileSelectionPreview() {
            return fileSelectionPreview
        }

        if let text = firstStringPreview() {
            return text
        }

        if let filePreview = firstFilePreview() {
            return filePreview
        }

        if let imagePreview = firstImagePreview() {
            return imagePreview
        }

        let typeNames = Set(items.flatMap { $0.types.map(\.rawValue) })
        if let first = typeNames.sorted().first {
            return "\(items.count) item\(items.count == 1 ? "" : "s") · \(first)"
        }

        return "\(items.count) item\(items.count == 1 ? "" : "s")"
    }

    var plainText: String? {
        firstPlainText()
    }

    var clipboardFreePasteText: String? {
        guard fileURLs.isEmpty, containsOnlyPlainTextItems else { return nil }
        return plainText
    }

    var fileSelectionBadgeText: String {
        guard fileURLs.count > 1 else { return "" }

        let categories = fileURLs.map(fileCategory)
        let uniqueKinds = Set(categories.map(\.countNoun))
        if uniqueKinds.count == 1, let category = categories.first {
            return countBadge(fileURLs.count, singular: category.countNoun, plural: category.pluralCountNoun)
        }

        let categoryCounts =
            categories
            .reduce(into: [String: Int]()) { counts, category in
                counts[category.countNoun, default: 0] += 1
            }
            .sorted { lhs, rhs in
                let lhsRank = FileSelectionCategory.displayRank(for: lhs.key)
                let rhsRank = FileSelectionCategory.displayRank(for: rhs.key)
                if lhsRank == rhsRank {
                    return lhs.value > rhs.value
                }
                return lhsRank < rhsRank
            }

        guard categoryCounts.count <= 2 else {
            return countBadge(fileURLs.count, singular: "item", plural: "items")
        }

        let categorySummary =
            categoryCounts
            .map { countBadge($0.value, singular: $0.key, plural: FileSelectionCategory.pluralCountNoun(for: $0.key)) }
            .joined(separator: ", ")

        return categorySummary.isEmpty ? countBadge(fileURLs.count, singular: "item", plural: "items") : categorySummary
    }

    var isTransient: Bool {
        items.contains { item in
            item.types.contains(NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
                || item.types.contains(NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
                || item.types.contains(NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
                || item.types.contains(
                    NSPasteboard.PasteboardType("com.trolltech.anymime.application--x-nspasteboard-concealed-type"))
        }
    }

    func hasSamePayload(as other: PasteboardSnapshot) -> Bool {
        guard fileURLs == other.fileURLs, items.count == other.items.count else { return false }
        return zip(items, other.items).allSatisfy { lhs, rhs in
            Set(lhs.types) == Set(rhs.types) && lhs.types.allSatisfy { lhs.data(forType: $0) == rhs.data(forType: $0) }
        }
    }

    private func firstPlainText() -> String? {
        for item in items {
            if let string = item.string(forType: .string) {
                let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
                if !trimmed.isEmpty {
                    return string
                }
            }
        }
        return nil
    }

    private var containsOnlyPlainTextItems: Bool {
        guard items.count == 1 else { return false }

        let allowedTypes: Set<String> = [
            NSPasteboard.PasteboardType.string.rawValue,
            "NSStringPboardType",
            "public.utf16-plain-text",
            "public.utf16-external-plain-text",
            "com.apple.traditional-mac-plain-text",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
        ]

        return items.allSatisfy { item in
            let typeNames = item.types.map(\.rawValue)
            return !typeNames.isEmpty && typeNames.allSatisfy { allowedTypes.contains($0) }
        }
    }

    private func firstStringPreview() -> String? {
        firstPlainText()?.oneLinePreview()
    }

    private func fileSelectionPreview() -> String? {
        guard !fileURLs.isEmpty else { return nil }

        if fileURLs.count == 1, let url = fileURLs.first {
            return "\(url.lastPathComponent) · \(singleFileDetail(for: url))"
        }

        let shownNames = fileURLs.prefix(3).map(\.lastPathComponent)
        let remainder = fileURLs.count - shownNames.count
        let suffix = remainder > 0 ? ", +\(remainder) more" : ""
        return "\(shownNames.joined(separator: ", "))\(suffix)"
    }

    private func firstFilePreview() -> String? {
        for item in items {
            guard
                let urlString = item.string(forType: .fileURL),
                let url = URL(string: urlString)
            else {
                continue
            }

            let size = fileSizeDescription(for: url)
            if let size {
                return "\(url.lastPathComponent) · \(size)"
            }
            return url.lastPathComponent
        }
        return nil
    }

    private func firstImagePreview() -> String? {
        for item in items {
            for type in [NSPasteboard.PasteboardType.png, .tiff] {
                if let data = item.data(forType: type) {
                    return "Image · \(ByteCountFormatter.string(fromByteCount: Int64(data.count), countStyle: .file))"
                }
            }
        }
        return nil
    }

    private func fileSizeDescription(for url: URL) -> String? {
        guard
            let values = try? url.resourceValues(forKeys: [.fileSizeKey]),
            let fileSize = values.fileSize
        else {
            return nil
        }

        return ByteCountFormatter.string(fromByteCount: Int64(fileSize), countStyle: .file)
    }

    private func singleFileDetail(for url: URL) -> String {
        let category = fileCategory(for: url)
        switch category {
        case .folder:
            return "Folder"
        case .package(let localizedDescription):
            return localizedDescription ?? "Package"
        case .file:
            return fileSizeDescription(for: url) ?? "File"
        }
    }

    private func fileCategory(for url: URL) -> FileSelectionCategory {
        let values = try? url.resourceValues(forKeys: [
            .isDirectoryKey,
            .isPackageKey,
            .localizedTypeDescriptionKey,
        ])

        if values?.isPackage == true {
            return .package(localizedDescription: values?.localizedTypeDescription)
        }

        if values?.isDirectory == true {
            return .folder
        }

        return .file
    }

    private func countBadge(_ count: Int, singular: String, plural: String) -> String {
        "\(count) \(count == 1 ? singular : plural)"
    }

}

private enum FileSelectionCategory {
    case file
    case folder
    case package(localizedDescription: String?)

    var countNoun: String {
        switch self {
        case .file:
            return "file"
        case .folder:
            return "folder"
        case .package(let localizedDescription):
            let description = localizedDescription?.lowercased() ?? ""
            if description.contains("project") {
                return "project"
            }
            if description.contains("application") || description == "app" {
                return "app"
            }
            return "package"
        }
    }

    var pluralCountNoun: String {
        Self.pluralCountNoun(for: countNoun)
    }

    static func pluralCountNoun(for noun: String) -> String {
        switch noun {
        case "app":
            return "apps"
        default:
            return "\(noun)s"
        }
    }

    static func displayRank(for noun: String) -> Int {
        switch noun {
        case "file":
            return 0
        case "folder":
            return 1
        case "project":
            return 2
        case "app":
            return 3
        case "package":
            return 4
        default:
            return 99
        }
    }
}

final class ClipboardRestorer {
    private let pasteboard: NSPasteboard
    private var temporaryOperationID: UUID?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    var isTemporaryOperationActive: Bool { temporaryOperationID != nil }

    func beginTemporaryOperation() -> UUID? {
        guard temporaryOperationID == nil else { return nil }
        let id = UUID()
        temporaryOperationID = id
        return id
    }

    func endTemporaryOperation(_ id: UUID) {
        guard temporaryOperationID == id else { return }
        temporaryOperationID = nil
    }

    private let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private let autogeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private let qtConcealedType = NSPasteboard.PasteboardType(
        "com.trolltech.anymime.application--x-nspasteboard-concealed-type")

    func snapshot() -> PasteboardSnapshot {
        let copiedItems: [NSPasteboardItem] =
            pasteboard.pasteboardItems?.map { item in
                let copy = NSPasteboardItem()
                for type in item.types {
                    if let data = item.data(forType: type) {
                        copy.setData(data, forType: type)
                    } else if let string = item.string(forType: type) {
                        copy.setString(string, forType: type)
                    }
                }
                return copy
            } ?? []

        let copiedFileURLs = copiedItems.compactMap { item -> URL? in
            guard let urlString = item.string(forType: .fileURL) else { return nil }
            return URL(string: urlString)
        }
        let fileURLs = copiedFileURLs.count == copiedItems.count ? copiedFileURLs : []

        return PasteboardSnapshot(items: copiedItems, fileURLs: fileURLs)
    }

    func snapshot(fileURLs: [URL]) -> PasteboardSnapshot {
        PasteboardSnapshot(items: filePasteboardItems(for: fileURLs), fileURLs: fileURLs)
    }

    func writeTextForTemporaryPaste(_ text: String) {
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        markTemporary(item)

        pasteboard.clearContents()
        pasteboard.writeObjects([item])
    }

    func writeTextForUserClipboard(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    func writeSnapshotForTemporaryPaste(_ snapshot: PasteboardSnapshot) {
        let sourceItems = snapshot.items.isEmpty ? filePasteboardItems(for: snapshot.fileURLs) : snapshot.items
        let temporaryItems = sourceItems.map { copyPasteboardItem($0, markAsTemporary: true) }

        pasteboard.clearContents()
        if !temporaryItems.isEmpty {
            writeItems(temporaryItems, to: pasteboard)
        }
    }

    func write(_ snapshot: PasteboardSnapshot) {
        pasteboard.clearContents()
        if !snapshot.items.isEmpty {
            writeItems(snapshot.items, to: pasteboard)
        } else if !snapshot.fileURLs.isEmpty {
            pasteboard.writeObjects(snapshot.fileURLs as [NSURL])
        }
    }

    func writeToUserClipboard(_ item: SelectionItem) {
        switch item.payload {
        case .text(let text):
            writeTextForUserClipboard(text)
        case .pasteboard(let snapshot):
            write(snapshot)
        }
    }

    func restore(_ snapshot: PasteboardSnapshot) {
        write(snapshot)
    }

    private func markTemporary(_ item: NSPasteboardItem) {
        item.setString("", forType: transientType)
        item.setString("", forType: autogeneratedType)
        // CopyQ recognizes the concealed MIME marker, but its Qt converter does
        // not map Apple's UTI to that MIME type. Publish both forms so a borrowed
        // transport stays out of native and Qt clipboard histories.
        item.setString("", forType: concealedType)
        item.setString("", forType: qtConcealedType)
    }

    private func copyPasteboardItem(_ original: NSPasteboardItem, markAsTemporary: Bool = false) -> NSPasteboardItem {
        let copy = NSPasteboardItem()
        for type in original.types {
            if let data = original.data(forType: type) {
                copy.setData(data, forType: type)
            } else if let string = original.string(forType: type) {
                copy.setString(string, forType: type)
            }
        }
        if markAsTemporary {
            markTemporary(copy)
        }
        return copy
    }

    private func writeItems(_ items: [NSPasteboardItem], to pasteboard: NSPasteboard) {
        // Pasteboard items already written to a board cannot be reused. Always
        // publish fresh, eagerly materialized copies, preserving all items/types.
        let copies = items.map { copyPasteboardItem($0) }.filter { !$0.types.isEmpty }
        if !copies.isEmpty { pasteboard.writeObjects(copies) }
    }

    private func filePasteboardItems(for urls: [URL]) -> [NSPasteboardItem] {
        urls.map { url in
            let item = NSPasteboardItem()
            item.setString(url.absoluteString, forType: .fileURL)
            item.setString(url.absoluteString, forType: .URL)
            item.setString(url.path, forType: .string)
            return item
        }
    }
}

extension String {
    func oneLinePreview(limit: Int = 96) -> String {
        let collapsed = components(separatedBy: .whitespacesAndNewlines)
            .filter { !$0.isEmpty }
            .joined(separator: " ")

        let safeLimit = max(0, limit)
        guard collapsed.count > safeLimit else { return collapsed }
        let index = collapsed.index(collapsed.startIndex, offsetBy: safeLimit)
        return String(collapsed[..<index]) + "..."
    }
}
